  with check ((bucket_id = 'interview-videos'::text));
create policy "Participants can upload their own interview videos" on storage.objects as PERMISSIVE for INSERT to authenticated
  with check (((bucket_id = 'interview-videos'::text) AND ((storage.foldername(name))[1] = (auth.uid())::text)));
create policy "Participants can view their own interview videos" on storage.objects as PERMISSIVE for SELECT to authenticated
  using (((bucket_id = 'interview-videos'::text) AND ((storage.foldername(name))[1] = (auth.uid())::text)));
create policy "Researchers can view participant interview videos" on storage.objects as PERMISSIVE for SELECT to authenticated
  using (((bucket_id = 'interview-videos'::text) AND (EXISTS ( SELECT 1
   FROM (interviews iv
     JOIN studies s ON ((s.id = iv.study_id)))
  WHERE ((s.researcher_id = auth.uid()) AND ((storage.foldername(objects.name))[1] = (iv.participant_id)::text))))));
create policy "Users can delete their own videos" on storage.objects as PERMISSIVE for DELETE to authenticated
  using (((bucket_id = 'interview-videos'::text) AND ((auth.uid())::text = (storage.foldername(name))[1])));
create policy "Users can view their own videos" on storage.objects as PERMISSIVE for SELECT to authenticated
  using (((bucket_id = 'interview-videos'::text) AND ((auth.uid())::text = (storage.foldername(name))[1])));

