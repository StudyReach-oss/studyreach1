CREATE OR REPLACE FUNCTION public.get_slot_availability(p_study_ids bigint[])
 RETURNS TABLE(study_id bigint, total integer, free integer)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select s.study_id, count(*)::integer as total,
         count(*) filter (where s.taken = false)::integer as free
  from public.slots s
  where s.study_id = any(p_study_ids)
  group by s.study_id;
$function$;

