CREATE OR REPLACE FUNCTION public.backfill_interview_quality(p_interview_id bigint, p_score integer, p_detail jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  update public.interviews i
     set quality_score = p_score,
         quality_detail = p_detail
   where i.id = p_interview_id
