CREATE OR REPLACE FUNCTION public.enforce_participation_quota()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_max integer;
  v_count integer;
begin
  -- Verrouille la ligne de l'étude pour sérialiser les insertions concurrentes
  select max_participants into v_max
  from public.studies
  where id = new.study_id
  for update;

  if v_max is null then
    return new; -- étude introuvable, on laisse la FK gérer l'erreur
  end if;

  select count(*) into v_count
  from public.participations
  where study_id = new.study_id
    and status in ('joined','interview','pending_validation','completed');

  if v_count >= v_max then
    raise exception 'Quota de participants atteint pour cette étude (% / %)', v_count, v_max
      using errcode = 'P0001';
  end if;

  return new;
end;
$function$;

