CREATE OR REPLACE FUNCTION public.refund_reject_participation(p_participation_id bigint)
 RETURNS numeric
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_part participations%rowtype;
  v_study studies%rowtype;
  v_wallet numeric;
begin
  -- Verrou : sérialise tout appel concurrent sur CETTE participation.
  select * into v_part from participations where id = p_participation_id for update;
  if not found then
    raise exception 'Participation introuvable';
  end if;

  select * into v_study from studies
   where id = v_part.study_id and researcher_id = auth.uid();
  if not found then
    raise exception 'Non autorise';
  end if;

  if v_part.paid = true then
    raise exception 'Participation deja validee et creditee';
  end if;

  -- Une participation déjà auto-validée (J14) a une garantie de paiement à J30 :
  -- on ne doit jamais pouvoir la refuser/rembourser après coup.
  if v_part.auto_validated = true then
    raise exception 'Participation deja auto-validee : paiement garanti, refus impossible';
  end if;

  if v_part.status = 'rejected' then
    select wallet into v_wallet from profiles where id = auth.uid();
    return v_wallet;
  end if;

  update participations set status = 'rejected' where id = p_participation_id;
  update interviews set status = 'rejected'
   where study_id = v_part.study_id and participant_id = v_part.participant_id
     and status = 'pending_validation';

  perform set_config('app.wallet_op','1',true);
  update profiles set wallet = round((coalesce(wallet,0) + coalesce(v_study.cost_per_participant,0))::numeric,2)
   where id = auth.uid();

  select wallet into v_wallet from profiles where id = auth.uid();
  return v_wallet;
end;
$function$;

CREATE OR REPLACE FUNCTION public.refund_study_close(p_study_id bigint)
 RETURNS numeric
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_study studies%rowtype;
  v_validated int;
  v_rejected int;
  v_refund_slots int;
  v_refund numeric;
  v_wallet numeric;
begin
  -- Verrou : sérialise tout appel concurrent sur CETTE étude.
  select * into v_study from studies
   where id = p_study_id and researcher_id = auth.uid() for update;
  if not found then
    raise exception 'Etude introuvable ou non autorisee';
  end if;

  if v_study.status = 'closed' then
    select wallet into v_wallet from profiles where id = auth.uid();
    return v_wallet;
  end if;

  -- "validés" = paiement déjà effectué OU déjà garanti par l'auto-validation J14.
  select count(*) into v_validated from participations
    where study_id = p_study_id and (paid = true or auto_validated = true);
  -- "rejected" = déjà remboursé au refus manuel. "abandoned" = déjà remboursé par
  -- le cron expire-participations (24h). Ne pas recompter (double remboursement).
  select count(*) into v_rejected from participations
    where study_id = p_study_id and status in ('rejected','abandoned');

  v_refund_slots := greatest(0, coalesce(v_study.max_participants,0) - v_validated - v_rejected);
  v_refund := round((v_refund_slots * coalesce(v_study.cost_per_participant,0))::numeric, 2);

  update studies set status = 'closed' where id = p_study_id;
  update participations set status = 'rejected'
   where study_id = p_study_id and status in ('pending_validation','joined','interview')
     and auto_validated is distinct from true;

  if v_refund > 0 then
    perform set_config('app.wallet_op','1',true);
    update profiles set wallet = round((coalesce(wallet,0) + v_refund)::numeric,2)
     where id = auth.uid();
  end if;

  select wallet into v_wallet from profiles where id = auth.uid();
  return v_wallet;
end;
$function$;

CREATE OR REPLACE FUNCTION public.request_email_change(p_new_email text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_new text := lower(trim(p_new_email));
  v_current text;
  v_token text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Non authentifie';
  END IF;
  IF v_new IS NULL OR v_new !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'Adresse email invalide';
  END IF;

  SELECT lower(email) INTO v_current FROM public.profiles WHERE id = auth.uid();
  IF v_new = v_current THEN
    RAISE EXCEPTION 'C''est deja votre adresse actuelle';
  END IF;

  IF EXISTS (SELECT 1 FROM public.profiles WHERE lower(email) = v_new AND id <> auth.uid())
     OR EXISTS (SELECT 1 FROM auth.users WHERE lower(email) = v_new AND id <> auth.uid()) THEN
    RAISE EXCEPTION 'Cette adresse email est deja utilisee';
  END IF;

  v_token := replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');

  UPDATE public.profiles
     SET pending_email = v_new, verification_token = v_token
   WHERE id = auth.uid();

  RETURN v_token;
END;
$function$;

