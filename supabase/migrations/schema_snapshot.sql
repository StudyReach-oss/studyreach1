CREATE OR REPLACE FUNCTION public.claim_fully_booked_email(p_study_id bigint)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_row_count integer;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.participations
    WHERE study_id = p_study_id AND participant_id = auth.uid()
  ) THEN
    RAISE EXCEPTION 'Non autorise';
  END IF;

  UPDATE public.studies
  SET fully_booked_email_sent_at = now()
  WHERE id = p_study_id
    AND fully_booked_email_sent_at IS NULL;
  GET DIAGNOSTICS v_row_count = ROW_COUNT;
  RETURN v_row_count > 0;
END;
$function$;

CREATE OR REPLACE FUNCTION public.confirm_email_change(p_uid uuid, p_token text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_new text;
BEGIN
  SELECT pending_email INTO v_new
    FROM public.profiles
   WHERE id = p_uid
     AND verification_token IS NOT NULL
     AND verification_token = p_token
     AND pending_email IS NOT NULL;

  IF v_new IS NULL THEN
    RAISE EXCEPTION 'Lien de confirmation invalide ou expire';
  END IF;

  IF EXISTS (SELECT 1 FROM public.profiles WHERE lower(email) = v_new AND id <> p_uid)
     OR EXISTS (SELECT 1 FROM auth.users WHERE lower(email) = v_new AND id <> p_uid) THEN
    -- Quelqu'un d'autre a pris cette adresse entre-temps : on annule proprement.
    UPDATE public.profiles SET pending_email = NULL, verification_token = NULL WHERE id = p_uid;
    RAISE EXCEPTION 'Cette adresse email vient d''etre prise par un autre compte';
  END IF;

  UPDATE public.profiles
     SET email = v_new, pending_email = NULL, verification_token = NULL, email_verified = true
   WHERE id = p_uid;

  UPDATE auth.users
     SET email = v_new,
         email_confirmed_at = now(),
         email_change = '',
         email_change_token_current = '',
         email_change_token_new = '',
         updated_at = now()
   WHERE id = p_uid;

  UPDATE auth.identities
     SET identity_data = jsonb_set(jsonb_set(coalesce(identity_data,'{}'::jsonb), '{email}', to_jsonb(v_new)), '{email_verified}', 'true'::jsonb),
         updated_at = now()
   WHERE user_id = p_uid AND provider = 'email';

  RETURN v_new;
END;
$function$;

