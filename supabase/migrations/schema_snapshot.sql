       or auth.uid() in (select s.researcher_id from public.studies s where s.id = i.study_id)
     );
end;
$function$;

CREATE OR REPLACE FUNCTION public.block_study_budget(p_study_id bigint)
 RETURNS numeric
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_study studies%rowtype;
  v_amount numeric;
  v_wallet numeric;
begin
  select * into v_study from studies
   where id = p_study_id and researcher_id = auth.uid()
   for update;
  if not found then
    raise exception 'Etude introuvable ou non autorisee';
  end if;

  if v_study.budget_blocked then
    select wallet into v_wallet from profiles where id = auth.uid();
    return v_wallet;
  end if;

  v_amount := round((coalesce(v_study.cost_per_participant,0) * coalesce(v_study.max_participants,0))::numeric, 2);

  select wallet into v_wallet from profiles where id = auth.uid() for update;
  if coalesce(v_wallet,0) < v_amount then
    raise exception 'Solde insuffisant';
  end if;

  perform set_config('app.wallet_op','1',true);
  update profiles set wallet = round((coalesce(wallet,0) - v_amount)::numeric,2)
   where id = auth.uid();
  update studies set budget_blocked = true where id = p_study_id;

  select wallet into v_wallet from profiles where id = auth.uid();
  return v_wallet;
end;
$function$;

