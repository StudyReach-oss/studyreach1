CREATE OR REPLACE FUNCTION public.verify_email(p_uid uuid, p_token text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  matched boolean;
BEGIN
  UPDATE public.profiles
     SET email_verified = true,
         verification_token = NULL
   WHERE id = p_uid
     AND verification_token IS NOT NULL
     AND verification_token = p_token
     AND email_verified = false;
  GET DIAGNOSTICS matched = ROW_COUNT;
  -- Renvoie true si on vient de valider, OU si déjà vérifié (lien cliqué 2 fois).
  RETURN matched OR EXISTS (SELECT 1 FROM public.profiles WHERE id = p_uid AND email_verified = true);
END;
$function$;

