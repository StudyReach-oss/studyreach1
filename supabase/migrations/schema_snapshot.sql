CREATE OR REPLACE FUNCTION public.guard_interview_terminal_status()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  if coalesce(auth.role(), '') = 'service_role' then
    return new;
  end if;

  if old.status in ('abandoned','rejected')
     and new.status is distinct from old.status then
    raise exception 'Entretien dans un etat terminal (%) : changement de statut non autorise', old.status;
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.guard_participation_payment_fields()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  if coalesce(auth.role(), '') = 'service_role' then
    return new;
  end if;

  if new.paid is not distinct from old.paid
     and new.paid_to_bank is not distinct from old.paid_to_bank
     and new.paid_at is not distinct from old.paid_at then
    return new;
  end if;

  if exists (
    select 1 from public.studies s
    where s.id = new.study_id and s.researcher_id = auth.uid()
  ) then
    return new;
  end if;

  raise exception 'Modification du statut de paiement non autorisee';
end;
$function$;

