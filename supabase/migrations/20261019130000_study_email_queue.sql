-- File d'attente serveur pour les emails "nouvelle étude" destinés aux participants NON Boost.
-- Ils doivent partir à la fin de l'accès anticipé (studies.early_access_until), même si le
-- chercheur ferme son navigateur : c'est pg_cron qui s'en charge, pas le navigateur.
-- L'application n'enregistre ici que (étude, participant) ; titre, thème, durée, email et
-- prénom sont relus en base au moment de l'envoi (impossible de faire envoyer un texte libre).
-- À appliquer AVANT de déployer le nouveau App.jsx.

create table if not exists public.study_email_queue (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  study_id bigint not null references public.studies(id) on delete cascade,
  participant_id uuid not null references public.profiles(id) on delete cascade,
  send_after timestamptz not null default now(),
  study_price numeric,
  study_type_label text,
  sent_at timestamptz,
  skipped boolean not null default false,
  unique (study_id, participant_id)
);
create index if not exists study_email_queue_due_idx
  on public.study_email_queue (send_after) where sent_at is null;

alter table public.study_email_queue enable row level security;
revoke all on public.study_email_queue from public, anon;
grant insert on public.study_email_queue to authenticated;

-- Un chercheur ne peut mettre en file que pour ses propres études. Personne ne peut lire la file.
drop policy if exists "Researchers queue emails for their own studies" on public.study_email_queue;
create policy "Researchers queue emails for their own studies" on public.study_email_queue
  as PERMISSIVE for INSERT to authenticated
  with check (exists (
    select 1 from public.studies s
    where s.id = study_id and s.researcher_id = auth.uid()
  ));

-- L'heure d'envoi est imposée par la base : fin de la fenêtre d'accès anticipé de l'étude.
create or replace function public.set_study_email_queue_send_after()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $$
begin
  new.send_after := coalesce((select s.early_access_until from public.studies s where s.id = new.study_id), now());
  new.sent_at := null;
  new.skipped := false;
  return new;
end;
$$;
drop trigger if exists trg_set_study_email_queue_send_after on public.study_email_queue;
create trigger trg_set_study_email_queue_send_after
  before insert on public.study_email_queue
  for each row execute function public.set_study_email_queue_send_after();

-- Envoi des emails arrivés à échéance, par petits lots (3 par passage) pour rester sous
-- la limite de débit de Resend (l'ancien envoi côté navigateur était espacé de 600 ms).
