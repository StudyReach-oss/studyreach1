-- Paiement par virement bancaire (institutions) : portefeuille crédité automatiquement à
-- réception du virement (Stripe, moyen de paiement "customer_balance"), et l'étude préparée par
-- le chercheur est publiée automatiquement une fois le virement reçu.
-- ⚠️ À appliquer AVANT de déployer le nouveau code (api/ + App.jsx).
--
-- Principe :
--   1) Le chercheur prépare son étude → elle est enregistrée avec status = 'pending_payment'
--      (invisible des participants : les règles RLS ne montrent que status = 'active').
--   2) Une "commande de virement" (bank_transfer_orders) lie le virement attendu à cette étude.
--   3) Le webhook Stripe crédite le portefeuille puis appelle activate_study_after_payment(),
--      qui bloque le budget, passe l'étude en 'active' et met en file les emails aux participants.
--   Tout est écrit par le serveur (service_role) : le navigateur ne peut rien se créditer.

-- 1) Infos de facturation + client Stripe du chercheur (écriture service_role uniquement)
create table if not exists public.researcher_billing (
  researcher_id uuid primary key references public.profiles(id) on delete cascade,
  stripe_customer_id text,
  billing_name text,
  billing_address text,
  billing_vat_number text,
  billing_siret text,
  updated_at timestamptz not null default now()
);
alter table public.researcher_billing enable row level security;
revoke all on public.researcher_billing from public, anon, authenticated;
grant select on public.researcher_billing to authenticated;
drop policy if exists "Researchers read own billing" on public.researcher_billing;
create policy "Researchers read own billing" on public.researcher_billing
  as PERMISSIVE for SELECT to authenticated
  using (researcher_id = auth.uid() or public.is_admin());

-- 2) Commandes de virement
create table if not exists public.bank_transfer_orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  researcher_id uuid references public.profiles(id) on delete set null,
  amount numeric(10,2) not null check (amount > 0),
  po_number text,                       -- n° de bon de commande de l'institution (facultatif)
  stripe_session_id text not null unique,
  stripe_payment_intent_id text,
  hosted_instructions_url text,         -- page Stripe avec IBAN / BIC / référence à communiquer à la compta
  status text not null default 'pending_checkout'
    check (status in ('pending_checkout','awaiting_transfer','paid','failed','expired')),
  study_id bigint references public.studies(id) on delete set null,
  email_queue jsonb not null default '[]'::jsonb,   -- participants à prévenir à la publication
  paid_at timestamptz,
  activated_at timestamptz,
  activation_result text
);
create index if not exists bank_transfer_orders_researcher_idx on public.bank_transfer_orders (researcher_id);
create index if not exists bank_transfer_orders_pi_idx on public.bank_transfer_orders (stripe_payment_intent_id);
-- une seule commande ouverte par étude
create unique index if not exists bank_transfer_orders_open_study_uniq
  on public.bank_transfer_orders (study_id)
  where study_id is not null and status in ('pending_checkout','awaiting_transfer');

alter table public.bank_transfer_orders enable row level security;
revoke all on public.bank_transfer_orders from public, anon, authenticated;
grant select on public.bank_transfer_orders to authenticated;
drop policy if exists "Researchers read own transfer orders" on public.bank_transfer_orders;
create policy "Researchers read own transfer orders" on public.bank_transfer_orders
  as PERMISSIVE for SELECT to authenticated
  using (researcher_id = auth.uid() or public.is_admin());

-- 3) Alertes pour l'admin (virement trop faible, excédent, échec, activation impossible…)
create table if not exists public.bank_transfer_alerts (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null,                   -- partial | overpaid | failed | expired | activation_failed | unmatched
  researcher_id uuid references public.profiles(id) on delete set null,
  order_id uuid references public.bank_transfer_orders(id) on delete set null,
  message text not null,
  details jsonb not null default '{}'::jsonb,
  resolved boolean not null default false
);
alter table public.bank_transfer_alerts enable row level security;
revoke all on public.bank_transfer_alerts from public, anon, authenticated;
grant select, update on public.bank_transfer_alerts to authenticated;
drop policy if exists "Admin reads transfer alerts" on public.bank_transfer_alerts;
create policy "Admin reads transfer alerts" on public.bank_transfer_alerts
  as PERMISSIVE for SELECT to authenticated using (public.is_admin());
drop policy if exists "Admin resolves transfer alerts" on public.bank_transfer_alerts;
create policy "Admin resolves transfer alerts" on public.bank_transfer_alerts
  as PERMISSIVE for UPDATE to authenticated using (public.is_admin()) with check (public.is_admin());

-- 4) Facture : n° de bon de commande + moyen de paiement
alter table public.invoices add column if not exists po_number text;
alter table public.invoices add column if not exists payment_method text default 'card';

-- 5) Publication automatique de l'étude une fois le virement reçu.
--    Appelée UNIQUEMENT par le webhook (service_role), APRÈS le crédit du portefeuille.
--    Idempotente : verrou sur la commande + sur l'étude, activated_at empêche tout double traitement
--    (y compris si deux événements Stripe arrivent en même temps).
create or replace function public.activate_study_after_payment(p_order_id uuid)
 returns text
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  o public.bank_transfer_orders%rowtype;
  s public.studies%rowtype;
  v_amount numeric;
  v_wallet numeric;
  v_result text;
  v_total_slots integer;
  v_future_slots integer;
  v_needed_slots integer;
begin
  select * into o from public.bank_transfer_orders where id = p_order_id for update;
  if not found then return 'no_order'; end if;
  if o.study_id is null then return 'no_study'; end if;
  if o.activated_at is not null then return 'already_active'; end if;

  select * into s from public.studies where id = o.study_id for update;
  if not found then
    update public.bank_transfer_orders set activation_result = 'study_missing' where id = o.id;
    return 'study_missing';
  end if;
  if s.status <> 'pending_payment' then
    update public.bank_transfer_orders set activation_result = coalesce(activation_result, 'not_pending') where id = o.id;
    return coalesce(o.activation_result, 'not_pending');
  end if;

  -- Protection créneaux : un virement peut arriver des jours (ou semaines) après la préparation de l'étude.
  -- Si les créneaux d'entretien prévus sont passés, on NE publie PAS une étude avec des créneaux morts :
  -- le portefeuille reste crédité, l'étude est abandonnée et le webhook alerte l'admin.
  -- Entretien individuel (video / inperson) : 1 place par créneau → il faut au moins autant de créneaux
  -- futurs que de participants visés. Autres types : au moins 1 créneau futur.
  select count(*), count(*) filter (where datetime > now())
    into v_total_slots, v_future_slots
    from public.slots where study_id = s.id;
  if v_total_slots > 0 then
    v_needed_slots := case when s.study_type in ('video','inperson') then greatest(coalesce(s.max_participants,1),1) else 1 end;
    if v_future_slots < v_needed_slots then
      update public.studies set status = 'abandoned' where id = s.id;
      update public.bank_transfer_orders set activation_result = 'slots_expired' where id = o.id;
      return 'slots_expired';
    end if;
  end if;

  v_amount := round((coalesce(s.cost_per_participant,0) * coalesce(s.max_participants,0))::numeric, 2);
  select wallet into v_wallet from public.profiles where id = o.researcher_id for update;
  if coalesce(v_wallet,0) < v_amount then
    update public.bank_transfer_orders set activation_result = 'insufficient_wallet' where id = o.id;
    return 'insufficient_wallet';
  end if;

  -- Blocage du budget (même logique que block_study_budget, mais pour le chercheur de la commande)
  if not coalesce(s.budget_blocked, false) then
    perform set_config('app.wallet_op','1',true);
    update public.profiles set wallet = round((coalesce(wallet,0) - v_amount)::numeric, 2) where id = o.researcher_id;
    update public.studies set budget_blocked = true where id = s.id;
  end if;

  -- Publication. La fenêtre d'accès anticipé Boost démarre MAINTENANT (et non à la création du brouillon).
  update public.studies
     set status = 'active',
         early_access_until = case
           when coalesce(is_test, false) then null
           else now() + make_interval(mins => public.boost_early_access_minutes())
         end
   where id = s.id;

  -- Emails "nouvelle étude" aux participants correspondants (heure d'envoi fixée par le trigger de la file)
  insert into public.study_email_queue (study_id, participant_id, study_price, study_type_label)
  select s.id, (e->>'participant_id')::uuid, nullif(e->>'study_price','')::numeric, nullif(e->>'study_type_label','')
    from jsonb_array_elements(o.email_queue) e
   where (e->>'participant_id') ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
     and exists (select 1 from public.profiles p where p.id = (e->>'participant_id')::uuid and p.role = 'participant')
  on conflict (study_id, participant_id) do nothing;

  v_result := 'activated';
  update public.bank_transfer_orders set activated_at = now(), activation_result = v_result where id = o.id;
  return v_result;
end;
$function$;
revoke all on function public.activate_study_after_payment(uuid) from public, anon, authenticated;
grant execute on function public.activate_study_after_payment(uuid) to service_role;
